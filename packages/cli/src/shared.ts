function withGeneratedHeader(content: string, header: string): string {
  if (content.startsWith('#!')) {
    const newline = content.indexOf('\n');
    if (newline === -1) return `${content}\n${header}`;
    return `${content.slice(0, newline + 1)}${header}${content.slice(newline + 1)}`;
  }
  return `${header}${content}`;
}

function generatedHeaderForTarget(target: KernTarget, relSource: string): string {
  const prefix = target === 'fastapi' || target === 'python' ? PYTHON_GENERATED_HEADER : GENERATED_HEADER;
  return `${prefix + relSource}\n\n`;
}

function withCommentPrefix(comment: string, prefix: '//' | '#'): string {
  return prefix === '#' ? comment.replace(/^\/\//, '#') : comment;
}

function escapeRegex(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

interface SourceTracePoint {
  comment: string;
  name: string;
  nodeType: string;
}

function collectSourceTracePoints(
  ast: IRNode,
  sourceName: string,
  commentPrefix: '//' | '#' = '//',
): SourceTracePoint[] {
  const nodes = [ast, ...(ast.children || [])];
  return nodes
    .filter((node) => node.loc && TRACEABLE_NODE_TYPES.has(node.type) && typeof node.props?.name === 'string')
    .map((node) => ({
      comment: withCommentPrefix(sourceComment(node, sourceName), commentPrefix),
      name: node.props!.name as string,
      nodeType: node.type,
    }))
    .filter((point) => point.comment.length > 0);
}

function declarationPatterns(point: SourceTracePoint): RegExp[] {
  const name = escapeRegex(point.name);
  return [
    new RegExp(`^(\\s*)(?:export\\s+)?(?:default\\s+)?(?:async\\s+)?function\\s+${name}\\b`),
    new RegExp(`^(\\s*)(?:export\\s+)?(?:default\\s+)?class\\s+${name}\\b`),
    new RegExp(`^(\\s*)(?:export\\s+)?const\\s+${name}\\b`),
    new RegExp(`^(\\s*)(?:export\\s+)?let\\s+${name}\\b`),
    new RegExp(`^(\\s*)(?:export\\s+)?interface\\s+${name}\\b`),
    new RegExp(`^(\\s*)(?:export\\s+)?type\\s+${name}\\b`),
    new RegExp(`^(\\s*)(?:export\\s+)?enum\\s+${name}\\b`),
    new RegExp(`^(\\s*)(?:async\\s+)?def\\s+${name}\\b`),
    new RegExp(`^(\\s*)class\\s+${name}\\b`),
  ];
}

function sourceTraceInsertIndex(lines: string[]): number {
  let index = 0;
  if (lines[index]?.startsWith('#!')) index += 1;
  if (/^(?:\/\/|#) @generated by kern\b/.test(lines[index] ?? '')) {
    index += 1;
    if (lines[index] === '') index += 1;
  }
  return index;
}

function entryTracePoints(points: SourceTracePoint[]): SourceTracePoint[] {
  for (let index = points.length - 1; index >= 0; index -= 1) {
    if (points[index].nodeType === 'screen') return [points[index]];
  }
  return points.length > 0 ? [points[0]] : [];
}

function withSourceTraceComments(
  content: string,
  ast: IRNode,
  sourceName: string,
  options: { entry?: boolean; commentPrefix?: '//' | '#' } = {},
): string {
  if (content.trim().length === 0) return content;
  if (SOURCE_TRACE_PATTERN.test(content)) return content;

  const collectedPoints = collectSourceTracePoints(ast, sourceName, options.commentPrefix);
  const points = options.entry ? entryTracePoints(collectedPoints) : collectedPoints;
  if (points.length === 0) return content;

  const lines = content.split('\n');
  const unmatched: string[] = [];

  for (const point of points) {
    let inserted = false;
    const patterns = declarationPatterns(point);

    for (let index = 0; index < lines.length; index += 1) {
      if (!patterns.some((pattern) => pattern.test(lines[index]))) continue;
      lines.splice(index, 0, point.comment);
      inserted = true;
      break;
    }

    if (!inserted) unmatched.push(point.comment);
  }

  if (unmatched.length > 0) {
    lines.splice(sourceTraceInsertIndex(lines), 0, ...unmatched, '');
  }

  return lines.join('\n');
}

/** Parse a [major, minor, patch] tuple from a generated-header line, or null if absent. */
function parseStampedVersion(file: string): [number, number, number] | null {
  let candidateLines: string[];
  try {
    const buf = readFileSync(file, 'utf-8');
    candidateLines = buf.split('\n').slice(0, 2);
  } catch {
    return null;
  }

  for (const line of candidateLines) {
    const match = line.match(STAMP_PATTERN);
    if (match) return [Number(match[1]), Number(match[2]), Number(match[3])];
  }

  return null;
}

export function parseCompilerVersion(version: string): [number, number, number] | null {
  const match = version.match(SEMVER_PREFIX_PATTERN);
  if (!match) return null;
  return [Number(match[1]), Number(match[2]), Number(match[3])];
}

function compareSemver(a: [number, number, number], b: [number, number, number]): number {
  for (let i = 0; i < 3; i++) {
    if (a[i] !== b[i]) return a[i] - b[i];
  }
  return 0;
}

function normalizeGeneratedHeaderVersion(content: string): string {
  return content.replace(GENERATED_HEADER_PATTERN, '$1 v<version>$2');
}

function differsOnlyByGeneratedHeaderVersion(existing: string, next: string): boolean {
  return existing !== next && normalizeGeneratedHeaderVersion(existing) === normalizeGeneratedHeaderVersion(next);
}

/**
 * Check the existing output file's @generated stamp against the current compiler version.
 * Emits a warning when the stamp is newer (downgrade) or older by a minor/major (drift).
 * Stays silent on patch-level drift and on first compile.
 */
export function checkVersionDrift(outFilePath: string, sourceFile: string): void {
  if (!existsSync(outFilePath)) return;
  const stamped = parseStampedVersion(outFilePath);
  if (!stamped) return;

  const current = parseCompilerVersion(KERN_VERSION);
  if (!current) return;

  const cmp = compareSemver(stamped, current);
  if (cmp === 0) return;

  if (cmp > 0) {
    console.warn(
      `  WARN kern-compiler-drift: ${sourceFile}: existing output was generated by kern v${stamped.join('.')}, but the active compiler is v${KERN_VERSION}. Re-compiling with an OLDER compiler may regress codegen features.`,
    );
    return;
  }

  // stamped is older than current
  if (stamped[0] !== current[0] || stamped[1] !== current[1]) {
    console.warn(
      `  INFO kern-compiler-drift: ${sourceFile}: existing output was generated by kern v${stamped.join('.')}, current compiler is v${KERN_VERSION}. Output will be re-generated.`,
    );
  }
}

function writeGeneratedFileSync(outFilePath: string, content: string, sourceFile: string): void {
  if (existsSync(outFilePath)) {
    const existing = readFileSync(outFilePath, 'utf-8');
    if (existing === content || differsOnlyByGeneratedHeaderVersion(existing, content)) return;
  }

  checkVersionDrift(outFilePath, sourceFile);
  writeFileSync(outFilePath, content);
}

