export function surfaceParseDiagnostics(
  diagnostics: ParseDiagnostic[],
  file?: string,
): { errors: number; warnings: number } {
  if (diagnostics.length === 0) return { errors: 0, warnings: 0 };
  const prefix = file ? `${file}: ` : '';
  let errors = 0;
  let warnings = 0;
  for (const diagnostic of diagnostics) {
    // Slice 5a: native-eligibility hints fire on every raw handler whose
    // body could opt in to lang="kern". They're surfaced via the API for
    // IDE integrations and the future `kern migrate native-handlers` CLI,
    // but printing them on every `kern compile` would flood CI logs and
    // user output. Skip from the default print path; dedicated commands
    // (gaps, migrate, review) can opt to surface them explicitly.
    if (diagnostic.code === 'NATIVE_KERN_ELIGIBLE') continue;
    const tag = diagnostic.severity === 'error' ? 'ERROR' : diagnostic.severity === 'warning' ? 'WARN' : 'INFO';
    console.error(`  ${prefix}[${tag}] ${diagnostic.code}: ${diagnostic.message}`);
    if (diagnostic.severity === 'error') errors++;
    else if (diagnostic.severity === 'warning') warnings++;
  }
  return { errors, warnings };
}

function validationViolations(root: IRNode): SchemaViolation[] {
  return [
    ...validateSchema(root),
    ...validateSemantics(root).map((sv) => ({
      nodeType: sv.nodeType,
      message: `[${sv.rule}] ${sv.message}`,
      line: sv.line,
      col: sv.col,
    })),
  ];
}

export function surfaceValidationDiagnostics(root: IRNode, file?: string): { errors: number; warnings: number } {
  const violations = validationViolations(root);
  if (violations.length === 0) return { errors: 0, warnings: 0 };
  const prefix = file ? `${file}: ` : '';
  for (const violation of violations) {
    const where = violation.line != null ? `:${violation.line}${violation.col != null ? `:${violation.col}` : ''}` : '';
    console.error(`  ${prefix}[ERROR] VALIDATION${where}: ${violation.message}`);
  }
  return { errors: violations.length, warnings: 0 };
}

export function parseAndSurface(
  source: string,
  file?: string,
  options?: import('@kernlang/core').ParseOptions,
  surfaceValidation = false,
): IRNode {
  const result = parseWithDiagnostics(source, undefined, options);
  surfaceParseDiagnostics(result.diagnostics, file);
  if (surfaceValidation) surfaceValidationDiagnostics(result.root, file);
  return result.root;
}

