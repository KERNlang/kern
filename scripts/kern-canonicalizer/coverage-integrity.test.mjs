test('the executed runtime catalog must exactly match the hashed constitution', () => {
  const constitution = JSON.parse(readFileSync(
    new URL('../kir-structural/constitution.json', import.meta.url),
    'utf8',
  ));
  assert.doesNotThrow(() => validateRuntimeCatalogConstitution(constitution, STRUCTURAL_KIR_NODE_CATALOG));
  const mutated = structuredClone(constitution);
  mutated.nodes[0].reasonId = `${mutated.nodes[0].reasonId}-drift`;
  assert.throws(
    () => validateRuntimeCatalogConstitution(mutated, STRUCTURAL_KIR_NODE_CATALOG),
    /runtime catalog does not match the structural constitution/u,
  );
  for (const mutate of [
    (copy) => { copy.future = true; },
    (copy) => { copy.properties.push(structuredClone(copy.properties[0])); },
    (copy) => { copy.properties[0].nodeKind = 'not-a-constitution-node'; },
  ]) {
    const malformed = structuredClone(constitution);
    mutate(malformed);
    assert.throws(
      () => validateRuntimeCatalogConstitution(malformed, STRUCTURAL_KIR_NODE_CATALOG),
      /runtime catalog does not match the structural constitution/u,
    );
  }
});
