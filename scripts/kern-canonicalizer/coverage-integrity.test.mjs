test('selection accepts only immutable facts created by the current measurement', () => {
  const policy = loadCoveragePolicy();
  const measured = measureCanonicalizerCoverage(policy);
  const clone = structuredClone(measured.functions);
  const driftedPolicy = structuredClone(policy);
  driftedPolicy.corpus[0].tool = 'invented-tool';
  assert.throws(() => measured.functions[0].excludedProperties.pop(), /read only|not extensible|Cannot delete/u);
  assert.throws(() => selectCanonicalizerTranche(policy, clone), /authenticated measurement/u);
  assert.throws(
    () => selectCanonicalizerTranche(driftedPolicy, measured.functions),
    /authenticated coverage policy/u,
  );
  assert.deepEqual(selectCanonicalizerTranche(policy, measured.functions), measured.selection);
});

