test('historical compiled core identities authenticate exact M4.145 membership', () => {
  const currentPaths = compiledCorePaths();
  const historicalPaths = reconstructM4145CompiledCoreJavaScriptPaths(currentPaths);
  const omitted = new Set(currentPaths.filter((path) => !historicalPaths.includes(path)));
  assert.deepEqual([...omitted].sort(), [
    'each-collection-reference.js',
    'kir-structural/branch-path-value.js',
    'kir-structural/each-collection-reference.js',
    'kir-structural/runtime-inflate.js',
    'kir-v1/canonical.js',
    'kir-v1/types.js',
    'runtime-envelope/kir-handler.js',
  ]);
  assert.equal(
    digestM4145CompiledCoreJavaScript(),
    '29daa6ca4f8017ea214b72434c92b00b33a92f328a9f49798264f5c94e51f5b2',
  );
  assert.notEqual(digestM4145CompiledCoreJavaScript(), compiledCoreDigest({ omitted }));
  assert.equal(
    digestPreM4135CompiledCoreJavaScript(),
    '502bde3b1a95cbafa2039a0227d626aeceb605c0d9de5ebe24183ab9b37f10ec',
  );
  const sibling = 'runtime-envelope/source-handler.js';
  assert.ok(historicalPaths.includes(sibling));
  const siblingBytes = readFileSync(resolve(process.cwd(), 'packages/core/dist', sibling));
  assert.notEqual(
    compiledCoreDigest({
      omitted,
      overrides: new Map([[sibling, Buffer.concat([siblingBytes, Buffer.from('\n')])]]),
    }),
    digestM4145CompiledCoreJavaScript(),
  );
});

test('historical structural constitution chains exact pre-lambda, pre-each, pre-branch, and pre-expression bytes', () => {
  const preLambda = loadPreLambdaRuntimeConstitutionSource();
  assert.equal(
    digest(preLambda),
    'f9bef5fa63a370d084ff324cf1257b05d30170a5bf86cfa03393ec341b5d47ae',
  );
  assert.equal(digest(resolveRuntimeConstitutionSource(preLambda)), digest(preLambda));
  const preEach = loadPreEachRuntimeConstitutionSource();
  assert.equal(
    digest(preEach),
    '7e1072291f97583b2fc27dcd033732a76db104e99ebf12b09d2c5907057e408c',
  );
  assert.equal(digest(resolveRuntimeConstitutionSource(preEach)), digest(preEach));
  const preBranch = loadPreBranchRuntimeConstitutionSource();
  assert.equal(
    digest(preBranch),
    'fad83fc3f7a4b2b7b5f6b89bff2a47721cc06f1bba8a13a9b55be0bba8997ed7',
  );
  assert.equal(digest(resolveRuntimeConstitutionSource(preBranch)), digest(preBranch));
  assert.equal(
    digest(loadPreExpressionV1RuntimeConstitutionSource()),
    'fa3a0cddc280ff2d8dd9f09cf575953b5adbaaf6f8c716c05e06faf2d43cd6ea',
  );
  assert.throws(
    () => measureCanonicalizerCoverage(undefined, undefined, { constitutionSource: 'invented' }),
    /coverage catalog rejection/u,
  );
  assert.throws(
    () => measureCanonicalizerCoverage(undefined, undefined, {
      constitutionSource: Buffer.from('{"attacker":"controlled"}'),
    }),
    /coverage catalog rejection/u,
  );
});

