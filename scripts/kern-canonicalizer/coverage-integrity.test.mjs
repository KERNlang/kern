test('handwritten corpus admission rejects every repository generated header variant', () => {
  const directory = repositoryCorpusFixture('generated-header');
  try {
    for (const [index, source] of [
      '\ufeff \t# GENERATED FILE — do not hand-edit.\n',
      '\ufeff \t# @generated by kern v5.0.0 — DO NOT EDIT.\n',
    ].entries()) {
      const path = join(directory, `${index}.kern`);
      writeFileSync(path, source);
      const policy = loadCoveragePolicy();
      policy.corpus = [{
        digest: digest(source),
        path: corpusPath(path),
        sourceKind: 'handwritten',
        tool: 'generated-probe',
      }];
      assert.throws(() => validateCoveragePolicy(policy), /corpus member .* is generated/u);
    }
  } finally {
    rmSync(directory, { force: true, recursive: true });
  }
});

