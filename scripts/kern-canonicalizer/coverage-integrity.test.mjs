function digest(value) {
  return createHash('sha256').update(value).digest('hex');
}

function corpusPath(path) {
  return relative(process.cwd(), path).split(sep).join('/');
}

function repositoryCorpusFixture(prefix) {
  // Keep transient corpus data outside the implementation tree: other test
  // workers authenticate that tree recursively while these fixtures are live.
  return mkdtempSync(join(process.cwd(), `.kern-canonicalizer-${prefix}-`));
}

function compiledCorePaths() {
  const root = resolve(process.cwd(), 'packages/core/dist');
  const files = [];
  function visit(directory) {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isSymbolicLink()) throw new TypeError(`compiled core entry ${path} must not be a symlink`);
      if (entry.isDirectory()) visit(path);
      else if (entry.isFile() && entry.name.endsWith('.js')) files.push(path);
    }
  }
  visit(root);
  return files.map((path) => relative(root, path).split(sep).join('/')).sort();
}

function compiledCoreDigest({ omitted = new Set(), overrides = new Map() } = {}) {
  const root = resolve(process.cwd(), 'packages/core/dist');
  const hash = createHash('sha256');
  for (const name of compiledCorePaths()) {
    if (omitted.has(name)) continue;
    const bytes = overrides.get(name) ?? readFileSync(resolve(root, name));
    hash.update(`${name.length}:${name}:${bytes.length}:`);
    hash.update(bytes);
  }
  return hash.digest('hex');
}

function framedDigest(paths) {
  const hash = createHash('sha256');
  for (const path of [...paths].sort()) {
    const bytes = readFileSync(resolve(process.cwd(), path));
    hash.update(`${path.length}:${path}:${bytes.length}:`);
    hash.update(bytes);
  }
  return hash.digest('hex');
}

